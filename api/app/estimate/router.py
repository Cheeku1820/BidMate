"""The ROM estimate route.

One read. Tenancy goes through `load_project` like every neighbour, so
another org's estimate answers 404 rather than 403 -- a cross-org probe
must not be able to use the status code to confirm a project exists
under a guessed id.

One write: the override. The assumptions themselves are generated by
the worker (`app.worker.estimate_job`); the only thing an estimator does
to this document is replace an assumed number with one they know, and
that routes through `commit()` as one undoable action like every other
manual edit.

The write answers with the whole document, the way the schedule routes
do: an override changes the budget range, a section tally, and the
qualifications block at once, so returning the row alone would leave
the screen reassembling a number itself.
"""
import uuid

from fastapi import APIRouter, Depends
from sqlalchemy.orm import Session as DbSession

from app.auth.dependencies import current_user
from app.db import get_db
from app.estimate import override as override_svc
from app.estimate.assemble import build_estimate_out
from app.estimate.schemas import AssumptionOverrideIn, EstimateOut
from app.identity.models import User
from app.takeoff.router import load_project

router = APIRouter(prefix="/api", tags=["estimate"])


@router.get("/projects/{project_id}/estimate", response_model=EstimateOut)
def get_estimate(project_id: uuid.UUID, user: User = Depends(current_user),
                 db: DbSession = Depends(get_db)) -> EstimateOut:
    project = load_project(project_id, db, user)
    return build_estimate_out(db, project)


@router.patch("/assumptions/{assumption_id}", response_model=EstimateOut)
def patch_assumption(assumption_id: uuid.UUID, body: AssumptionOverrideIn,
                     user: User = Depends(current_user),
                     db: DbSession = Depends(get_db)) -> EstimateOut:
    row = override_svc.load_assumption(assumption_id, db, user)
    override_svc.override(db, row=row, actor=user, value=body.value, unit=body.unit)
    project = load_project(row.project_id, db, user)
    out = build_estimate_out(db, project)
    db.commit()
    return out
